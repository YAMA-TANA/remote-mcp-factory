import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';

const source = readFileSync(new URL('../src/picosvc/mail-advanced.ts', import.meta.url), 'utf8');
const entry = readFileSync(new URL('../src/picosvc-entry.ts', import.meta.url), 'utf8');
const routes = readFileSync(new URL('../src/picosvc/routes.ts', import.meta.url), 'utf8');
const sql = readFileSync(new URL('../migrations/0022_picosvc_mail_delivery.sql', import.meta.url), 'utf8');
assert.match(source, /AES-GCM/, 'Mail signing secret must be encrypted');
assert.match(source, /HMAC.*SHA-256/, 'Mail delivery must sign webhooks');
assert.match(source, /x-picosvc-mail-signature/, 'Mail signature header required');
assert.match(source, /x-picosvc-mail-timestamp/, 'Mail signature needs replay-protection timestamp');
assert.match(source, /MAX_ATTEMPTS = 4/, 'Mail retries must be bounded');
assert.match(source, /RETRY_MINUTES = \[1, 5, 15\]/, 'Mail retry must back off');
assert.match(source, /delivery_status='sending',attempts=attempts\+1/, 'Mail retries must claim work atomically');
assert.match(source, /WHERE id=\? AND delivery_status IN \('pending','retry'\)/, 'Mail retries must only claim pending work');
assert.match(source, /mail_attachments WHERE id=\? AND event_id=\? AND owner=\?/, 'Attachments must be owner scoped');
assert.match(source, /picosvc\/mail\/\$\{route\.id\}\/\$\{eventId\}/, 'Mail R2 keys must be event-scoped');
assert.match(source, /deletePrefix\(env, `picosvc\/mail\//, 'Mail event/route R2 cleanup required');
assert.match(source, /pruneMailR2Owner/, 'Mail retention must clean up R2');
assert.match(entry, /handleIncomingMailAdvanced\(message, env(?:,|\))/, 'Advanced inbound handler must be wired');
assert.match(entry, /runMailRetries\(env(?:,|\))/, 'Scheduled retry worker must be wired');
assert.ok(entry.indexOf('pruneMailR2Owners(env)') < entry.indexOf('picoSvcScheduledGuardrails(env)'), 'R2 must be cleaned before legacy D1 pruning');
assert.ok(routes.indexOf('mailAdvancedManagementRoutes,') < routes.indexOf('mailManagementRoutes,'), 'Advanced Mail management must be prioritized');

const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
db.exec(`CREATE TABLE mail_routes(id TEXT PRIMARY KEY, owner TEXT); CREATE TABLE mail_events(id TEXT PRIMARY KEY,route_id TEXT,owner TEXT,delivery_status TEXT, FOREIGN KEY(route_id) REFERENCES mail_routes(id));`);
db.exec(sql);
db.prepare('INSERT INTO mail_routes(id,owner) VALUES (?,?)').run('route-1','owner-1');
db.prepare("INSERT INTO mail_events(id,route_id,owner,delivery_status,next_retry_at) VALUES (?,?,?,?,?)").run('event-1','route-1','owner-1','pending',null);
const claim = db.prepare(`UPDATE mail_events SET delivery_status='sending',attempts=attempts+1,next_retry_at=NULL WHERE id=? AND delivery_status IN ('pending','retry') AND (next_retry_at IS NULL OR next_retry_at<=?) RETURNING id,attempts`);
assert.equal(claim.get('event-1', new Date().toISOString()).attempts, 1);
assert.equal(claim.get('event-1', new Date().toISOString()), undefined, 'Duplicate worker must not claim the same delivery');
db.prepare("UPDATE mail_events SET delivery_status='retry',next_retry_at=? WHERE id=?").run('2099-01-01T00:00:00Z','event-1');
assert.equal(claim.get('event-1', '2026-09-16T00:00:00Z'), undefined, 'Backoff must not be bypassed');
assert.equal(claim.get('event-1', '2099-01-01T00:00:00Z').attempts, 2);
assert.throws(() => db.prepare('INSERT INTO mail_attachments(id,event_id,route_id,owner,filename,content_type,size_bytes,r2_key,created_at) VALUES (?,?,?,?,?,?,?,?,?)').run('bad','missing','route-1','owner-1','x','text/plain',1,'x','now'), /FOREIGN KEY/);
db.close();
console.log('PicoSvc Mail delivery OK: signed workflow, owner scope, atomic retry claim, backoff, R2 cleanup invariants.');
