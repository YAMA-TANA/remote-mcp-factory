import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { filterFleet, fleetPaths, readFleetEvents, readFleetItems } from '../web/app/service-fleet-model.ts';
const source = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const cronId = '1a254cb8-5430-4edc-94f7-9e223544aaaa';
const mailId = '2a254cb8-5430-4edc-94f7-9e223544bbbb';
const cron = readFleetItems({ ownerId: 'private-owner', jobs: [{ id: cronId, name: 'Daily export', enabled: true, cron: '0 0 * * *', timezone: 'UTC', method: 'POST', targetUrl: 'https://api.example.com/export?token=secret', headers_json: '{"x-api-key":"secret"}', body: 'password=secret', lastRunAt: '2026-09-21T00:00:00.000Z' }] }, 'cron');
assert.equal(cron.length, 1);
assert.equal(cron[0].description, '0 0 * * *');
assert.match(cron[0].secondary, /api\.example\.com/);
assert.doesNotMatch(JSON.stringify(cron), /password|token=secret|x-api-key|private-owner/);
const mailAddress = 'a'.repeat(32) + '@picosvc.com';
const mail = readFleetItems({ routes: [{ id: mailId, name: 'Orders', enabled: false, address: mailAddress, webhookUrl: 'https://secret.example/?token=secret', signingSecret: 'hidden', createdAt: '2026-09-20T00:00:00.000Z' }] }, 'mail');
assert.equal(mail[0].description, mailAddress);
assert.equal(mail[0].enabled, false);
assert.doesNotMatch(JSON.stringify(mail), /secret\.example|signingSecret/);
assert.deepEqual(filterFleet([...cron, ...mail], '', 'enabled').map(item => item.id), [cronId]);
assert.deepEqual(filterFleet([...cron, ...mail], 'ORDERS', 'paused').map(item => item.id), [mailId]);
assert.deepEqual(filterFleet(cron, 'secret', 'all'), [], 'Secret query/path must not be exposed in search projection');
const runs = readFleetEvents({ runs: [{ id: cronId, error: null, response_status: 204, duration_ms: 53, ran_at: '2026-09-21T00:00:00.000Z', response_body: 'secret' }, { id: mailId, error: 'Secret endpoint error', response_status: 502, ran_at: '2026-09-21T01:00:00.000Z' }] }, 'cron');
assert.deepEqual(runs.map(run => run.status), ['ok','failed']);
assert.doesNotMatch(JSON.stringify(runs), /Secret|response_body/);
const deliveries = readFleetEvents({ events: [{ id: mailId, delivery_status: 'retry', attempts: 2, response_status: 503, received_at: '2026-09-21T00:00:00.000Z', from_address: 'private@example.com', subject: 'Secret order', text_preview: 'private body', payload_r2_key: 'private-path' }, { id: cronId, delivery_status: 'quota_reached', attempts: 0 }] }, 'mail');
assert.deepEqual(deliveries.map(event => event.status), ['pending','failed']);
assert.doesNotMatch(JSON.stringify(deliveries), /private@example|Secret order|private body|private-path/);
assert.equal(fleetPaths('cron', cronId).detail, `/api/picosvc/cron/jobs/${cronId}/runs`);
assert.equal(fleetPaths('mail', mailId).detail, `/api/picosvc/mail/routes/${mailId}/events`);
assert.equal(fleetPaths('mail').toggle, null);
assert.throws(() => fleetPaths('cron', '../other'), /Invalid resource ID/);
assert.throws(() => readFleetItems({ jobs: [{ ...cron[0], id: 'bad' }] }, 'cron'), /Invalid fleet resource/);
assert.throws(() => readFleetItems({ jobs: [{ ...cron[0], id: cronId }, { ...cron[0], id: cronId }] }, 'cron'), /Invalid fleet resource/);
assert.throws(() => readFleetEvents({ events: [{ delivery_status: 'undefined' }] }, 'mail'), /Invalid mail delivery status/);
const route = source('web/app/[locale]/[service]/manage/page.tsx');
const ui = source('web/app/service-fleet-console.tsx');
const header = source('web/app/customer-workspace-header.tsx');
assert.match(route, /'cron', 'mail'/);
assert.match(route, /generateStaticParams/);
assert.match(ui, /readFleetItems\(await request\(fleetPaths\(service\)\.list\), service\)/);
assert.match(ui, /readFleetEvents\(payload, service\)/);
assert.match(ui, /JSON\.stringify\(\{ enabled: !item\.enabled \}\)/, 'PATCH sends only enabled state');
assert.match(ui, /window\.confirm/, 'Disabling routes must require confirmation');
assert.match(ui, /requestVersion\.current/, 'Discard stale account fetches');
assert.match(header, /\$\{service\}\/manage\//, 'Link fleet consoles from workspace headers');
assert.match(source('web/app/service-fleet-console.css'), /@media\(max-width:480px\)/);
console.log('PicoSvc Cron/Mail fleet consoles: scoped routes, safe projections, status filtering, history, toggles, localization and responsive layout OK.');
