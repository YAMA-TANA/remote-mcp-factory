import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { mockRequestBody } from '../web/app/mock-form.ts';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const page = read('web/app/[locale]/mock/app/page.tsx');
const consoleSource = read('web/app/mock-app-workspace.tsx');
const css = read('web/app/mock-app-workspace.css');
const mockApi = read('src/picosvc/mock.ts');
const advancedApi = read('src/picosvc/mock-advanced.ts');
assert.match(page, /<MockAppWorkspace\s*\/>/, 'App route must use the dedicated resource console');
assert.match(consoleSource, /mockRequestBody\(form\)/, 'Keep existing validated endpoint inputs');
for (const route of ['/api/picosvc/mock/endpoints', '/rules', '/requests?limit=100']) assert.ok(consoleSource.includes(route), `Missing ${route} management route`);
assert.match(consoleSource, /window\.confirm\(t\.confirmRemove\)/, 'Deleting an endpoint must be confirmed');
assert.match(consoleSource, /window\.confirm\(t\.confirmRule\)/, 'Deleting a rule must be confirmed');
assert.match(consoleSource, /Promise\.all\(/, 'Load rule and request data together');
assert.match(consoleSource, /requestSequence\.current/, 'Ignore stale requests after switching resource');
assert.match(consoleSource, /role="alert"/, 'Expose API errors accessibly');
assert.match(consoleSource, /requestNote: '直近最大100件。リクエスト本文・ヘッダーはこの画面に表示しません。'/);
assert.doesNotMatch(consoleSource, /dangerouslySetInnerHTML|entry\.headers|entry\.bodyPreview|entry\.bodyBase64/, 'Never execute response HTML or expose logged request bodies/headers');
assert.match(mockApi, /WHERE id=\? AND owner=\?/, 'Mock management must scope endpoints to owner');
assert.match(advancedApi, /WHERE endpoint_id=\? AND owner=\?/, 'Rules and request history must be owner scoped');
assert.match(css, /@media\(max-width:760px\)/, 'Support small screens');
assert.throws(() => mockRequestBody({ name:'x',method:'GET',path:'/bad path/',statusCode:'200',contentType:'text/plain',body:'',enabled:true }), /Path/);
assert.equal(mockRequestBody({ name:'x',method:'POST',path:'/api/test/',statusCode:'201',contentType:'application/json',body:'{}',enabled:true }).path, 'api/test');
console.log('PicoSvc Mock app: per-endpoint management, safety and backend contracts OK.');
