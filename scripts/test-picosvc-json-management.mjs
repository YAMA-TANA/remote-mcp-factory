import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = name => readFileSync(new URL(`../${name}`, import.meta.url), 'utf8');
const ui = read('web/app/service-json-management.tsx');
const dispatcher = read('web/app/service-resource-detail.tsx');
const legacy = read('web/app/service-resource-detail-legacy.tsx');
const backend = read('src/picosvc/json-advanced.ts');
const management = read('src/picosvc/data-services.ts');
const styles = read('web/app/service-json-management.css');

assert.match(dispatcher, /service === 'json'\) return <JsonManagementDetail/, 'JSON must open dedicated manager');
for (const service of ['forms', 'license', 'flags']) assert.match(dispatcher, new RegExp(`service === '${service}'\\) return <`), `${service} keeps its dedicated manager`);
assert.match(dispatcher, /<LegacyServiceResourceDetail/, 'Files still uses legacy upload manager');
assert.match(legacy, /async function uploadFile\(/, 'File upload remains available');
assert.match(ui, /Object\.prototype\.hasOwnProperty\.call\(result, 'value'\)/, 'A null JSON value must not be mistaken for a missing document');
assert.match(ui, /setDocValue\(JSON\.stringify\(result\.value, null, 2\)\)/, 'Read document values without null coalescing');
assert.doesNotMatch(ui, /result\.value\s*\?\?/, 'Never replace a null document with its response envelope');
assert.match(ui, /new TextEncoder\(\)\.encode\(JSON\.stringify\(value\)\)\.byteLength > 256 \* 1024/, 'Validate document size in UTF-8');
assert.match(ui, /loadedDocKey !== docKey && !window\.confirm\(t\.overwrite\)/, 'Warn before an unconditional, unread-key overwrite');
assert.match(ui, /!window\.confirm\(t\.deleteConfirm\)/, 'Confirm document deletion');
assert.match(ui, /api\(`\$\{base\}\/settings`\)/, 'Read owner-authenticated access settings');
assert.match(ui, /method: 'PATCH'[\s\S]*?JSON\.stringify\(\{ publicRead \}\)/, 'Save access settings through authenticated API');
assert.match(ui, /publicRead \? t\.publicConfirm : t\.privateConfirm/, 'Confirm changes to public exposure');
assert.match(ui, /Promise\.all\(\[api\(`\$\{base\}\/settings`\), api\(`\$\{base\}\/tokens`\)\]\)/, 'Load scoped token inventory through management API');
assert.match(ui, /method: 'POST'[\s\S]*?JSON\.stringify\(\{ label: label\.trim\(\) \|\| 'Scoped token', scope,/, 'Issue labeled, scoped tokens');
assert.match(ui, /\.\.\.\(prefix \? \{ keyPrefix: prefix \} : \{\}\)/, 'Omit empty prefix to request unrestricted scope, as backend requires');
assert.match(ui, /setOneTimeToken\(result\.bearerToken\)/, 'Display one-time tokens only from issuance or rotation');
assert.match(ui, /api\(`\$\{base\}\/token\/rotate`, \{ method: 'POST' \}\)/, 'Allow explicit master token rotation');
assert.match(ui, /api\(`\$\{base\}\/tokens\/\$\{encodeURIComponent\(tokenId\)\}`, \{ method: 'DELETE' \}\)/, 'Allow scoped token revocation');
assert.match(ui, /api\(`\$\{base\}\/export\$\{after \?/, 'Load the bounded owner-authenticated export');
assert.match(ui, /encodeURIComponent\(after\)/, 'URL-encode the export cursor');
assert.match(ui, /nextCursor: exportCursor \|\| null/, 'Download clearly paginated exports with a continuation cursor');
assert.match(backend, /SELECT id,label,scope,key_prefix,expires_at,created_at FROM json_store_tokens/, 'Never return token hashes in listings');
assert.match(backend, /key\.startsWith\(scoped\.key_prefix\)/, 'Scoped key prefix is enforced by runtime');
assert.match(backend, /WHERE store_id=\? AND key>\? ORDER BY key LIMIT 101/, 'Export is paginated and bounded');
assert.match(management, /suffix === 'token\/rotate' && request\.method === 'POST'/, 'Master token can rotate without exposing stored hashes');
assert.match(styles, /@media\(max-width:540px\)/, 'JSON manager supports narrow screens');
console.log('PicoSvc JSON console contracts OK: null document reads, scoped secrets, public-read controls and bounded export.');
