import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';

const management = readFileSync(new URL('../src/picosvc/functions-advanced.ts', import.meta.url), 'utf8');
const runtime = readFileSync(new URL('../src/picosvc/functions-runtime-advanced.ts', import.meta.url), 'utf8');
const entry = readFileSync(new URL('../src/picosvc-entry.ts', import.meta.url), 'utf8');
const routes = readFileSync(new URL('../src/picosvc/routes.ts', import.meta.url), 'utf8');
const sql = readFileSync(new URL('../migrations/0024_picosvc_function_revisions.sql', import.meta.url), 'utf8');
assert.match(management, /function_revisions/, 'Revision snapshots required');
assert.match(management, /current_revision=\? AND code=\?/, 'Revision edits must compare existing state');
assert.match(management, /suffix === 'rollback'/, 'Rollback endpoint missing');
assert.match(management, /function_secrets WHERE app_id=\? AND owner=\?/, 'Function secrets must be owner-scoped');
assert.match(management, /AES-GCM/, 'Secrets must be encrypted');
assert.match(management, /MAX_SECRETS = 20/, 'Secret count must be capped');
assert.match(management, /MAX_LOGS = 200/, 'Execution log history must be bounded');
assert.match(runtime, /MAX_REQUEST_BYTES = 1024 \* 1024/, 'Function requests must be bounded');
assert.match(runtime, /MAX_RESPONSE_BYTES = 1024 \* 1024/, 'Function responses must be bounded');
assert.match(runtime, /MAX_FUNCTION_CPU_MS = 10/, 'Function CPU ceiling must remain economical');
assert.match(runtime, /MAX_FUNCTION_WALL_MS = 5_000/, 'Function wall timeout required');
assert.match(runtime, /MAX_SUBREQUESTS = 32/, 'Subrequest ceiling required');
assert.match(runtime, /\.\.\.secrets, PICOSVC_FUNCTION_ID/, 'Encrypted secrets must be passed into Function environment');
assert.match(runtime, /recordFunctionInvocation\(env, app.id, app.owner/, 'Function calls must log outcome');
assert.ok(entry.indexOf('functionsAdvancedRuntimeRoute,') < entry.indexOf('functionRuntimeRoute,'), 'Advanced runtime must intercept before legacy handler');
assert.ok(routes.indexOf('functionsAdvancedManagementRoutes,') < routes.indexOf('functionManagementRoutes,'), 'Versioned management must intercept legacy edits');

const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
db.exec('CREATE TABLE function_apps(id TEXT PRIMARY KEY,owner TEXT NOT NULL,code TEXT NOT NULL,updated_at TEXT NOT NULL)');
db.prepare('INSERT INTO function_apps(id,owner,code,updated_at) VALUES (?,?,?,?)').run('app-a','owner-a','export default {fetch(){return new Response("old")}}','2026-09-16T00:00:00Z');
db.exec(sql);
assert.equal(db.prepare('SELECT current_revision FROM function_apps WHERE id=?').get('app-a').current_revision, 1);
assert.equal(db.prepare('SELECT revision_no,code FROM function_revisions WHERE app_id=?').get('app-a').revision_no, 1, 'Existing functions must receive an initial revision');
assert.equal(db.prepare('SELECT code FROM function_revisions WHERE app_id=?').get('app-a').code.includes('old'), true);
db.prepare('UPDATE function_apps SET code=?,current_revision=current_revision+1 WHERE id=?').run('new','app-a');
db.prepare('INSERT INTO function_revisions(id,app_id,owner,revision_no,code,created_at) VALUES (?,?,?,?,?,?)').run('revision-b','app-a','owner-a',2,'new','now');
assert.throws(() => db.prepare('INSERT INTO function_revisions(id,app_id,owner,revision_no,code,created_at) VALUES (?,?,?,?,?,?)').run('dup','app-a','owner-a',2,'bad','now'), /UNIQUE/);
assert.throws(() => db.prepare('INSERT INTO function_secrets(app_id,owner,name,iv,ciphertext,updated_at) VALUES (?,?,?,?,?,?)').run('missing','owner','KEY','iv','cipher','now'), /FOREIGN KEY/);
db.prepare('DELETE FROM function_apps WHERE id=?').run('app-a');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM function_revisions').get().n, 0, 'Function deletion must clean revisions');
db.close();
console.log('PicoSvc advanced Functions OK: revision backfill, rollback, secret scope, limits and cleanup.');
