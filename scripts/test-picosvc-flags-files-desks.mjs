import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dataPaths, parseDataProjects, parseFiles, parseFlags, prepareFlag, publicDataUrl, validFilePath } from '../web/app/service-flags-files-model.ts';

const id = '11111111-2222-4333-8444-555555555555';
const publicId = 'a'.repeat(32);
const secret = { owner: 'SECRET_OWNER', token_hash: 'SECRET_HASH', webhook_url: 'https://secret.invalid', value_json: 'SECRET_VALUE_JSON' };
const flagsProject = parseDataProjects({ projects: [{ id, public_id: publicId, name: 'Production', ...secret }] }, 'flags');
assert.deepEqual(flagsProject, [{ id, publicId, name: 'Production', enabled: true }]);
assert.ok(!JSON.stringify(flagsProject).includes('SECRET_'));
const spaces = parseDataProjects({ spaces: [{ id, public_id: publicId, name: 'Assets', enabled: 0, ...secret }] }, 'files');
assert.equal(spaces[0].enabled, false);
assert.ok(!JSON.stringify(spaces).includes('SECRET_'));
assert.throws(() => parseDataProjects({ projects: [{ id, public_id: publicId, name: 'one' }, { id, public_id: publicId, name: 'two' }] }, 'flags'));
assert.throws(() => parseDataProjects({ spaces: [{ id, public_id: publicId, name: 'Bad', enabled: 'yes' }] }, 'files'));
const flags = parseFlags({ flags: [{ key: 'release.v2', enabled: 1, value: { ready: true }, updatedAt: '2026-09-21T01:00:00Z', ...secret }] });
assert.deepEqual(flags, [{ key: 'release.v2', enabled: true, value: { ready: true }, updatedAt: '2026-09-21T01:00:00Z' }]);
assert.ok(!JSON.stringify(flags).includes('SECRET_'));
assert.throws(() => parseFlags({ flags: [{ key: '../bad', enabled: true, value: true }] }));
assert.throws(() => parseFlags({ flags: [{ key: 'ok', enabled: true, value: true }, { key: 'ok', enabled: true, value: false }] }));
assert.throws(() => parseFlags({ flags: [{ key: 'ok', enabled: true, value: 'x'.repeat(32769) }] }));
assert.deepEqual(prepareFlag('ready', '{"ok":true}', false), { key: 'ready', value: { ok: true }, enabled: false });
assert.throws(() => prepareFlag('ready', 'null', true));
assert.throws(() => prepareFlag('ready', '{bad}', true));
assert.throws(() => prepareFlag('a/b', 'true', true));
const result = parseFiles({ storageUsedBytes: 1024, storageLimitBytes: null, objects: [{ path: 'assets/logo.png', content_type: 'image/png', size_bytes: 1024, updated_at: '2026-09-21T01:00:00Z', etag: 'SECRET_ETAG', body: 'SECRET_BODY', ...secret }] });
assert.deepEqual(result, { files: [{ path: 'assets/logo.png', contentType: 'image/png', size: 1024, updatedAt: '2026-09-21T01:00:00Z' }], used: 1024, limit: null });
assert.ok(!JSON.stringify(result).includes('SECRET_'));
assert.throws(() => parseFiles({ storageUsedBytes: -1, storageLimitBytes: null, objects: [] }));
assert.throws(() => parseFiles({ storageUsedBytes: 0, storageLimitBytes: 100, objects: [{ path: '../private', content_type: 'text/plain', size_bytes: 2 }] }));
assert.throws(() => parseFiles({ storageUsedBytes: 0, storageLimitBytes: 100, objects: [{ path: 'ok', content_type: 'text/plain', size_bytes: 1 }, { path: 'ok', content_type: 'text/plain', size_bytes: 1 }] }));
for (const bad of ['', '../x', 'a/../b', '/etc/passwd', 'a//b', 'a\nb']) assert.equal(validFilePath(bad), false);
assert.equal(validFilePath('images/example 1.png'), true);
assert.equal(dataPaths('flags').list, '/api/picosvc/flags/projects');
assert.equal(dataPaths('flags', id).children, `/api/picosvc/flags/projects/${id}/flags`);
assert.equal(dataPaths('flags', id, 'one.two').flag, `/api/picosvc/flags/projects/${id}/flags/one.two`);
assert.equal(dataPaths('files', id).children, `/api/picosvc/files/spaces/${id}/objects`);
assert.equal(dataPaths('files', id, 'folder/name #1.png').object, `/api/picosvc/files/spaces/${id}/object?path=folder%2Fname%20%231.png`);
assert.throws(() => dataPaths('files', '../../etc', 'okay'));
assert.throws(() => dataPaths('flags', id, '../secret'));
assert.equal(publicDataUrl('flags', 'https://api.example/x', publicId), `https://api.example/flags/${publicId}`);
assert.equal(publicDataUrl('files', 'https://api.example/x', publicId, 'folder/name #1.png'), `https://api.example/files/${publicId}/folder/name%20%231.png`);
assert.throws(() => publicDataUrl('flags', 'javascript:alert(1)', publicId));
assert.throws(() => publicDataUrl('files', 'https://user:password@api.example', publicId, 'x'));
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const page = read('web/app/[locale]/[service]/manage/page.tsx');
const header = read('web/app/customer-workspace-header.tsx');
const component = read('web/app/service-flags-files-desk.tsx');
const css = read('web/app/service-flags-files-desk.css');
const workflow = read('.github/workflows/ci.yml');
for (const service of ['flags', 'files']) assert.ok(page.includes(`'${service}'`) && header.includes(`service === '${service}'`));
assert.ok(page.includes('generateStaticParams') && page.includes('ServiceFlagsFilesDesk'));
assert.ok(component.includes('instance.addListener') && component.includes('<Editor key={revision}'), 'Identity changes must remount editor');
assert.ok(component.includes('window.confirm(t.removeFlagConfirm)') && component.includes('window.confirm(t.deleteFileConfirm)') && component.includes('window.confirm(t.uploadConfirm)'), 'Destructive actions must be confirmed');
assert.ok(component.includes('window.confirm(t.disableConfirm)') && component.includes('window.confirm(t.unsaved)'), 'Disable and discard require confirmation');
assert.ok(component.includes('upload.size > 10 * 1024 * 1024') && component.includes('prepareFlag('), 'Enforce upload and JSON guardrails');
assert.ok(component.includes('setFlags([]); setFiles([])') && component.includes('detailVersion.current'), 'Do not leak stale project data');
assert.ok(css.includes('@media(max-width:480px)'), 'Mobile stylesheet required');
assert.ok(workflow.includes('scripts/test-picosvc-flags-files-desks.mjs'));
console.log('Flags/Files management models, secret-safe projections, routes and UI wiring: passed');
