import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { filterMcpFleet, mcpPaths, parseMcpEvents, parseMcpFleet, parseMcpMetrics } from '../web/app/mcp-fleet-model.ts';
const source = file => readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');
const id = 'mcp-12345678';
const jobs = parseMcpFleet([{ id, name: 'Search MCP', status: 'ready', enabled: 1, branch: 'main', detected_runtime: 'edge', repo_url: 'https://github.com/x/repo?token=private-token', token_hash: 'private-hash', error: 'private-error', updated_at: '2026-09-21T00:00:00.000Z' }, { id: 'mcp-87654321', name: 'Billing', status: 'failed', enabled: 1, branch: 'main', detected_runtime: 'sandbox', repo_url: 'https://user:secret@github.com/x/repo' }, { id: 'mcp-99999999', name: 'Inactive', status: 'ready', enabled: 0 }]);
assert.equal(jobs.length, 3);
assert.equal(jobs[0].runtime, 'edge');
assert.doesNotMatch(JSON.stringify(jobs), /private-token|private-hash|private-error|user:secret/);
assert.deepEqual(filterMcpFleet(jobs, '', 'running').map(item => item.id), [id]);
assert.deepEqual(filterMcpFleet(jobs, '', 'attention').map(item => item.id), ['mcp-87654321']);
assert.deepEqual(filterMcpFleet(jobs, '', 'paused').map(item => item.id), ['mcp-99999999']);
assert.deepEqual(filterMcpFleet(jobs, 'BILLING', 'all').map(item => item.id), ['mcp-87654321']);
assert.deepEqual(filterMcpFleet(jobs, 'private-token', 'all'), []);
assert.equal(mcpPaths(id).toggle, `/api/servers/${id}`);
assert.equal(mcpPaths(id).metrics, `/api/picosvc/mcp/servers/${id}/metrics?days=30`);
assert.equal(mcpPaths(id).logs, `/api/picosvc/mcp/servers/${id}/logs?limit=30`);
assert.throws(() => mcpPaths('../admin'), /Invalid MCP ID/);
assert.throws(() => parseMcpFleet([{ ...jobs[0], id: '../bad' }]), /Invalid MCP deployment/);
assert.throws(() => parseMcpFleet([{ ...jobs[0] }, { ...jobs[0] }]), /Invalid MCP deployment/);
const metrics = parseMcpMetrics({ days: 30, ownerId: 'secret', summary: { requests: 100, errors: 5, averageDurationMs: 17.3, extra: 'private' }, daily: [{ extra: 'private' }] });
assert.deepEqual(metrics, { requests: 100, errors: 5, averageDurationMs: 17.3, errorRate: 0.05, days: 30 });
assert.throws(() => parseMcpMetrics({ days: 30, summary: { requests: 1, errors: 2, averageDurationMs: 1 } }), /Invalid MCP metrics/);
assert.throws(() => parseMcpMetrics({ days: 30, summary: { requests: -1, errors: 0, averageDurationMs: 1 } }), /Invalid MCP metrics/);
const events = parseMcpEvents({ events: [{ kind: 'build', status: 'ready', http_status: null, duration_ms: 25, created_at: '2026-09-21T00:00:00Z', message: 'Sensitive GitHub token', deployment_secret: 'topsecret' }] });
assert.equal(events[0].kind, 'build');
assert.doesNotMatch(JSON.stringify(events), /Sensitive|token|topsecret/);
assert.throws(() => parseMcpEvents({ events: [{ kind: 'build' }, null] }), /Invalid MCP log entry/);
const route = source('web/app/[locale]/[service]/manage/page.tsx');
const ui = source('web/app/mcp-fleet-console.tsx');
assert.match(route, /'mcp', 'cron', 'mail'/);
assert.match(route, /<McpFleetConsole \/>/);
assert.match(ui, /parseMcpFleet\(await request\(mcpPaths\(\)\.list\)\)/);
assert.match(ui, /Promise\.all\(\[request\(endpoints\.metrics\), request\(endpoints\.logs\)\]\)/);
assert.match(ui, /JSON\.stringify\(\{ enabled: !item\.enabled \}\)/, 'MCP update does not mutate secrets or access mode');
assert.match(ui, /window\.confirm\(t\.confirm\)/, 'Pausing a deployed MCP requires confirmation');
assert.match(ui, /scope\.current\+\+/, 'Clear stale owner-scoped data after account changes');
assert.match(source('web/app/customer-workspace-header.tsx'), /service === 'mcp'/, 'MCP workspace links to fleet control room');
assert.match(source('web/app/mcp-fleet-console.css'), /@media\(max-width:480px\)/);
console.log('PicoSvc MCP fleet: owner-safe fields, metrics, logs, URL paths, filtering, pause controls, localization and mobile styling OK.');
