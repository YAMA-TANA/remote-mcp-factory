import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import {
  deskPaths, filterDeskItems, parseActivationCount, parseDeskItems, parseFormDeliveries, parseFormSettings,
  parseFormSubmissions, parseLicenseKeys, parseValidations, prepareFormSettings, publicFormEndpoint,
} from '../web/app/service-customer-desk-model.ts';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const uuid = '11111111-2222-4333-8444-555555555555';
const uuid2 = '22222222-3333-4444-8555-666666666666';
const secret = 'TOP_PRIVATE_TOKEN_123';
const project = { id: uuid, public_id: 'a'.repeat(32), name: 'Demo', enabled: 1, updated_at: '2026-09-21T00:00:00Z', owner: secret, token_hash: secret };
const forms = parseDeskItems({ forms: [project] }, 'forms');
const licenses = parseDeskItems({ projects: [{ ...project, enabled: undefined }] }, 'license');
assert.equal(forms[0].enabled, true);
assert.equal(licenses[0].enabled, true);
assert.equal(filterDeskItems(forms, 'DEMO', 'enabled').length, 1);
assert.equal(filterDeskItems(forms, '', 'paused').length, 0);
assert.equal(filterDeskItems(licenses, 'demo', 'all').length, 1);
assert.ok(!JSON.stringify([...forms, ...licenses]).includes(secret));
assert.throws(() => parseDeskItems({ forms: [project, project] }, 'forms'));
assert.throws(() => parseDeskItems({ forms: [{ ...project, id: '../escape' }] }, 'forms'));
assert.deepEqual(deskPaths('forms', uuid).config, `/api/picosvc/forms/${uuid}/config`);
assert.deepEqual(deskPaths('forms', uuid).search, `/api/picosvc/forms/${uuid}/search`);
assert.deepEqual(deskPaths('license', uuid).keys, `/api/picosvc/license/projects/${uuid}/keys`);
assert.deepEqual(deskPaths('license', uuid, uuid2).validations, `/api/picosvc/license/keys/${uuid2}/validations`);
assert.throws(() => deskPaths('license', '../escape'));
assert.throws(() => deskPaths('license', uuid, '../escape'));
assert.equal(publicFormEndpoint('https://worker.example/api', forms[0]), `https://worker.example/forms/${'a'.repeat(32)}`);
assert.throws(() => publicFormEndpoint('javascript:alert(1)', forms[0]));
assert.throws(() => publicFormEndpoint('https://user:pass@worker.example', forms[0]));
const config = parseFormSettings({ allowedOrigins: ['https://example.com'], requiredFields: ['email'], honeypotField: '_website', requireTurnstile: true, webhookUrl: `https://private.example/${secret}`, successRedirect: 'https://site.example/thanks', owner: secret });
assert.equal(config.requireTurnstile, true);
assert.equal(JSON.stringify(config).includes('"owner"'), false);
const prepared = prepareFormSettings({ ...config, allowedOrigins: [' https://example.com ', 'https://example.com'], requiredFields: ['email', 'email'] });
assert.deepEqual(prepared.allowedOrigins, ['https://example.com']);
assert.deepEqual(prepared.requiredFields, ['email']);
assert.equal(prepared.webhookUrl, config.webhookUrl, 'Saving intake settings must preserve existing webhook target');
assert.equal(prepared.successRedirect, config.successRedirect, 'Saving intake settings must preserve existing redirect');
for (const origin of ['http://example.com', 'https://user:pass@example.com', 'https://example.com/path', 'https://example.com/?token=secret']) assert.throws(() => prepareFormSettings({ ...config, allowedOrigins: [origin] }));
assert.throws(() => prepareFormSettings({ ...config, requiredFields: ['invalid field'] }));
const submissions = parseFormSubmissions({ submissions: [{ id: uuid, payload: { email: secret }, headers: { Authorization: secret }, receivedAt: '2026-09-21T01:00:00Z' }], nextBefore: null });
assert.equal(submissions.entries.length, 1);
assert.ok(!JSON.stringify(submissions).includes(secret), 'Never display received payload or request headers');
const deliveries = parseFormDeliveries({ deliveries: [{ id: uuid, destination: `https://private.example/${secret}`, error: secret, response_status: 503, delivered_at: '2026-09-21T02:00:00Z' }] });
assert.equal(deliveries[0].delivered, false);
assert.equal(deliveries[0].status, 503);
assert.ok(!JSON.stringify(deliveries).includes(secret), 'Never display delivery target or raw error');
const keys = parseLicenseKeys({ keys: [{ id: uuid, label: 'Seat', revoked: 0, expires_at: '2026-09-20T00:00:00Z', created_at: '2026-09-01T00:00:00Z', licenseKey: secret, metadata: { token: secret }, customer_ref: secret }] }, Date.parse('2026-09-21T00:00:00Z'));
assert.equal(keys[0].expired, true);
assert.equal(keys[0].revoked, false);
assert.ok(!JSON.stringify(keys).includes(secret), 'Never retain license secrets or customer metadata');
const validations = parseValidations({ validations: [{ valid: 0, reason: 'revoked', device_hash: secret, checked_at: '2026-09-21T00:00:00Z' }, { valid: 1, reason: secret, device_hash: secret }] });
assert.equal(validations[0].reason, 'revoked');
assert.equal(validations[1].reason, 'other');
assert.ok(!JSON.stringify(validations).includes(secret), 'Never retain device hashes or untrusted reasons');
assert.equal(parseActivationCount({ activations: [{ device_hash: secret }, { device_hash: secret }] }), 2);
const page = read('web/app/[locale]/[service]/manage/page.tsx');
const header = read('web/app/customer-workspace-header.tsx');
const component = read('web/app/service-customer-desk.tsx');
const ci = read('.github/workflows/ci.yml');
for (const service of ['forms', 'license']) assert.ok(page.includes(`'${service}'`) && header.includes(`service === '${service}'`), `${service} must have localized navigation`);
assert.ok(component.includes('<Editor key={revision}') && component.includes('instance.addListener'), 'Account and organization switches must replace the editor');
assert.ok(component.includes('window.confirm(entry.revoked ? t.restoreConfirm : t.revokeConfirm)'), 'Key revocation and restoration require confirmation');
assert.ok(component.includes('prepareFormSettings') && component.includes('parseFormSubmissions') && component.includes('parseFormDeliveries'));
assert.ok(ci.includes('scripts/test-picosvc-customer-desks.mjs'), 'New safety regressions must run in CI');
console.log('Forms/License individual consoles: paths, allowlist privacy, origin validation, editing and navigation passed');
