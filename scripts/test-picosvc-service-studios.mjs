import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const page = read('web/app/[locale]/[service]/app/page.tsx');
const studio = read('web/app/service-studio.tsx');
const style = read('web/app/service-studio.css');
const management = read('web/app/service-management-detail.tsx');
const managementStyle = read('web/app/service-management-detail.css');
const routing = read('web/app/service-advanced-detail.tsx');
const legacy = read('web/app/service-advanced-detail-legacy.tsx');
const links = read('web/app/service-link-management.tsx');
const linkStyle = read('web/app/service-link-management.css');
const runtime = read('web/app/service-runtime-management.tsx');
const runtimeStyle = read('web/app/service-runtime-management.css');
const qrApi = read('src/picosvc/utility-services.ts');
const mailApi = read('src/picosvc/mail-service.ts');
const functionsApi = read('src/picosvc/functions-service.ts');
const monitorApi = read('src/picosvc/automation-services.ts');
const routes = ['mcp', 'rss', 'mail', 'qr', 'cron', 'functions', 'json', 'files', 'license', 'flags', 'monitor', 'forms'];
for (const slug of routes) {
  assert.match(studio, new RegExp(`\\b${slug}: \\{`), `Missing ${slug} service description`);
  assert.match(studio, new RegExp(`case '${slug}':`), `Missing ${slug} service composer`);
}
assert.match(page, /<ServiceStudio service=\{service\}/, 'Service pages must use purpose-built studios');
assert.match(page, /service === 'fetch' \? <FetchWorkspace/, 'Keep dedicated Fetch UI');
assert.match(page, /service === 'shot' \? <ShotWorkspace/, 'Keep dedicated Shot UI');
assert.match(studio, /workspaceIsSecret\(key\)/, 'Protect one-time credentials');
assert.match(studio, /const body = serviceRequestBody\(service, form\)/, 'Preserve validated API requests');
assert.match(studio, /<ServiceResourceDetail/, 'Preserve resource-specific operations');
assert.match(studio, /<ServiceAdvancedDetail/, 'Preserve advanced resource operations');
assert.match(studio, /role="alert"/, 'Expose API errors to assistive technology');
assert.match(studio, /aria-pressed=\{filter === key\}/, 'Expose filter selection');
assert.match(style, /@media/, 'Provide responsive layout');
for (const [service, component] of [['rss', 'RssManagementDetail'], ['cron', 'CronManagementDetail'], ['qr', 'QrManagementDetail'], ['mail', 'MailManagementDetail']]) {
  assert.match(routing, new RegExp(`props\\.service === '${service}'.*<${component}`), `${service} must open dedicated management`);
}
assert.match(routing, /props\.service === 'functions'.*<FunctionWorkspace/, 'Functions must open their composed management view');
assert.match(routing, /function FunctionWorkspace[\s\S]*?<FunctionsManagementDetail/, 'Functions must retain their source editor');
assert.match(routing, /function FunctionWorkspace[\s\S]*?<FunctionOperations/, 'Functions must expose advanced operations');
assert.match(routing, /props\.service === 'monitor'.*<MonitorWorkspace/, 'Monitor must open its composed management view');
assert.match(routing, /function MonitorWorkspace[\s\S]*?<MonitorManagementDetail/, 'Monitor must retain its status view');
assert.match(routing, /function MonitorWorkspace[\s\S]*?<MonitorOperations/, 'Monitor must expose advanced diagnostics');
assert.match(routing, /<LegacyServiceAdvancedDetail/, 'Unmigrated services must retain management actions');
assert.match(legacy, /async function rotate\(/, 'Retain MCP secret and token management');
assert.match(management, /\/preview.*method: 'POST'/, 'RSS must use its existing metered extraction endpoint');
assert.match(management, /\/refresh.*method: 'POST'/, 'RSS must use its existing metered refresh endpoint');
assert.match(management, /Array\.isArray\(result\.items\)/, 'RSS preview must verify an article list');
assert.match(management, /<article key=/, 'RSS articles must be displayed as readable cards');
assert.match(management, /api\(`\$\{base\}\/runs`\)/, 'Cron must load real run history');
for (const property of ['timezone', 'expectedStatus', 'maxRetries', 'notificationUrl']) assert.match(management, new RegExp(`\\b${property}:`), `Cron must expose ${property}`);
assert.match(management, /relatedAttempts = attempts\.filter/, 'Cron must associate retry attempts with each run');
assert.match(management, /relatedNotices = notifications\.filter/, 'Cron must associate failure alerts with each run');
assert.match(management, /safeUrl\(draft\.targetUrl\)/, 'Management URL validation must stay in place');
assert.match(managementStyle, /@media/, 'Management screens must remain responsive');
assert.match(links, /export function QrManagementDetail/, 'QR management component missing');
assert.match(links, /export function MailManagementDetail/, 'Mail management component missing');
assert.match(links, /\/api\/picosvc\/qr\/links\//, 'QR must use the real management route');
assert.match(links, /\$\{redirectUrl\}\.svg/, 'QR must use the existing public SVG endpoint');
assert.match(links, /current\.scans/, 'QR must show persisted scan counts');
assert.match(links, /safeWeb\(target\)/, 'QR must validate destination before saving');
assert.match(links, /\/api\/picosvc\/mail\/routes\//, 'Mail must use the real route');
assert.match(links, /api\(`\$\{base\}\/events`\)/, 'Mail must load delivery events');
assert.match(links, /Array\.isArray\(result\.events\)/, 'Mail must validate event responses');
assert.match(links, /delivery_status/, 'Mail must display actual delivery statuses');
assert.doesNotMatch(links, /rawBase64|bodyBase64/, 'Do not expose raw mail bodies in management UI');
assert.match(qrApi, /svgMatch/, 'QR public SVG must exist server-side');
assert.match(mailApi, /routeMatch\[2\] === 'events'/, 'Mail event endpoint must exist server-side');
assert.match(linkStyle, /@media/, 'QR and Mail screens must work on mobile');
assert.match(runtime, /export function FunctionsManagementDetail/, 'Functions must have a dedicated editor');
assert.match(runtime, /api\(base\)/, 'Functions editor must fetch the full source before editing');
assert.match(runtime, /new TextEncoder\(\)\.encode\(draft\.code\)\.byteLength/, 'Validate function code using UTF-8 size');
assert.match(runtime, /64 \* 1024/, 'Enforce function source size limit');
assert.match(runtime, /setSaved\(next\)/, 'Track saved state without discarding draft');
assert.match(runtime, /export function MonitorManagementDetail/, 'Monitor must have a dedicated status view');
assert.match(runtime, /api\('\/api\/picosvc\/monitor'\)/, 'Monitor must fetch real persisted check timestamps');
assert.match(runtime, /last_checked_at/, 'Monitor must display the latest check attempt');
assert.match(runtime, /last_changed_at/, 'Monitor must display recorded changes');
assert.match(runtime, /minIntervalMinutes/, 'Monitor must respect plan minimum intervals');
assert.match(runtime, /Number\.isSafeInteger/, 'Monitor must reject invalid check intervals');
assert.match(runtime, /window\.confirm\(t\.confirm\)/, 'Require confirmation before deletion');
assert.match(functionsApi, /const MAX_CODE_BYTES = 64 \* 1024/, 'Functions code size must match backend');
assert.match(monitorApi, /minIntervalMinutes/, 'Monitor tier minimum must exist server-side');
assert.match(runtimeStyle, /@media/, 'Functions and Monitor screens must work on mobile');
console.log('PicoSvc six dedicated management flows: routing, API contracts, size/interval guards and responsive UI OK.');
