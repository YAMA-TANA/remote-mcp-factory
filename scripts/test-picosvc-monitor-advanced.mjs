import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { normalizeMonitorText, readableMonitorDiff, validStripPattern } from '../src/picosvc/monitor-text.ts';
const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
assert.equal(normalizeMonitorText('  Ａ  \n  B  ', null), 'A B');
assert.equal(normalizeMonitorText('Total 123 dollars', '\\d'), 'Total dollars');
assert.equal(validStripPattern('(a+)+'), null);
assert.equal(validStripPattern('a{1,100}'), null);
assert.match(readableMonitorDiff('old value', 'new value'), /Before:.*old/);
const src = read('src/picosvc/monitor-advanced.ts');
const routes = read('src/picosvc/routes.ts');
const entry = read('src/picosvc-entry.ts');
for (const term of ['content_selector', 'ignore_selector', 'strip_pattern', 'fetch_error', 'readableMonitorDiff', 'webhook_status', "monitor', 'checks", 'm.enabled=0 AND o.enabled=1', 'last_content_hash', 'runAdvancedMonitorChecks']) assert.ok(src.includes(term), `Missing Monitor feature: ${term}`);
assert.ok(routes.indexOf('monitorAdvancedManagementRoutes,') < routes.indexOf('automationManagementRoutes,'));
assert.ok(entry.includes('await runAdvancedMonitorChecks(env'));
const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON'); db.exec(read('schema.sql'));
for (const file of readdirSync(new URL('../migrations/', import.meta.url)).filter((file) => /^00(?:1[0-9]|[2-9][0-9])_.*\.sql$/.test(file) && Number(file.slice(0,4)) >= 10).sort()) db.exec(read(`migrations/${file}`));
const now = '2026-09-16T00:00:00.000Z';
db.prepare('INSERT INTO monitors(id,owner,name,target_url,enabled,created_at,updated_at) VALUES(?,?,?,?,0,?,?)').run('m1','owner-a','Monitor','https://example.com',now,now);
db.prepare('INSERT INTO monitor_options(monitor_id,owner,enabled,content_selector,created_at,updated_at) VALUES(?,?,?,?,?,?)').run('m1','owner-a',1,'main',now,now);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM monitors m JOIN monitor_options o ON o.monitor_id=m.id AND o.owner=m.owner WHERE m.enabled=0 AND o.enabled=1').get().n, 1);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM monitors WHERE enabled=1').get().n, 0, 'Legacy monitor must not double-run');
db.prepare('INSERT INTO monitor_events(id,monitor_id,owner,event_type,diff_text,created_at) VALUES(?,?,?,?,?,?)').run('e1','m1','owner-a','change','Before: a\nAfter: b',now);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM monitor_events WHERE owner=?').get('owner-b').n, 0);
db.prepare('DELETE FROM monitors WHERE id=?').run('m1');
for (const table of ['monitor_options','monitor_events']) assert.equal(db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n, 0);
assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(), []);
db.close();
console.log('Monitor advanced normalization, isolated scheduling and event schema smoke OK.');
